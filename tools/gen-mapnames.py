#!/usr/bin/env python3
"""从原版服务端的 LS2MAP 地图文件头读取 floor 编号和地图名，生成 server/gamedata/mapnames_gen.go。

文件头格式见 docs/map.md：魔数 LS2MAP(6) + floor(u16) + 地图名(32 字节 GBK，\\0 结尾)，数值为大端。
地图名里 `|` 及其后面的内容去掉。用法：python3 tools/gen-mapnames.py
"""
import os
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP_DIR = os.path.join(ROOT, "original-data/gmsv/data/map")
OUT = os.path.join(ROOT, "server/gamedata/mapnames_gen.go")


def main():
    names = {}
    for dirpath, dirs, files in os.walk(MAP_DIR):
        dirs.sort()  # 遍历顺序固定，同一 floor 有两个名字时每次取同一个
        for f in sorted(files):
            with open(os.path.join(dirpath, f), "rb") as fh:
                head = fh.read(40)
            if len(head) < 40 or head[:6] != b"LS2MAP":
                continue
            floor = struct.unpack(">H", head[6:8])[0]
            raw = head[8:40].split(b"\0", 1)[0]
            name = raw.decode("gbk", errors="replace").split("|", 1)[0].strip()
            if floor in names and names[floor] != name:
                print(f"警告：floor {floor} 有两个名字 {names[floor]!r} / {name!r}，取先读到的", file=sys.stderr)
                continue
            names[floor] = name
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("// Code generated by tools/gen-mapnames.py; DO NOT EDIT.\n\n")
        out.write("package gamedata\n\n")
        out.write("// mapNames 是 floor 编号到地图名（UTF-8，已去掉 `|` 后缀）的对照表，来自旧地图文件头。\n")
        out.write("var mapNames = map[int]string{\n")
        for floor in sorted(names):
            out.write(f"\t{floor}: {names[floor]!r},\n".replace("'", '"'))
        out.write("}\n")
    subprocess.run(["gofmt", "-w", OUT], check=False)
    print(f"{len(names)} 个地图 → {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
