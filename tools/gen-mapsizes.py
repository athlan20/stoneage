#!/usr/bin/env python3
"""生成地图尺寸表（STAGE-152）。

遇敌区域的矩形是数据表里写死的，个别行会写到地图外面（例如地图 500 的 (1,1)-(800,800)，
而地图是 800×800，合法坐标 0..799）。场景页的“遇敌”列要选一个真正能站人的代表落点，
所以需要知道每张地图的格子宽高，把矩形裁到边界内。

尺寸从原版服务端的 LS2MAP 文件头读：
  0..6    "LS2MAP"
  6..8    地图号（大端 uint16）
  8..40   名字（GBK，32 字节）
  40..44  宽、高（大端 uint16，单位是格）
  44..    地块数组，宽×高 个 uint16

一个地图号有多个文件时取先扫到的那个并给出诊断。

用法：python3 tools/gen-mapsizes.py [地图目录]
"""

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_MAP_DIR = ROOT / "original-data/gmsv/data/map"
OUT = ROOT / "server/gamedata/mapsizes_gen.go"


def scan(map_dir: Path):
    sizes, dup = {}, []
    for path in sorted(map_dir.rglob("*")):
        if not path.is_file():
            continue
        try:
            head = path.open("rb").read(44)
        except OSError:
            continue
        if len(head) < 44 or head[:6] != b"LS2MAP":
            continue
        floor = struct.unpack(">H", head[6:8])[0]
        w, h = struct.unpack(">HH", head[40:44])
        if floor in sizes:
            if sizes[floor] != (w, h):
                dup.append(f"地图 {floor} 有多份文件且尺寸不同：{sizes[floor]} vs {(w, h)}（取前者）")
            continue
        sizes[floor] = (w, h)
    return sizes, dup


def main():
    map_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_MAP_DIR
    sizes, dup = scan(map_dir)
    if not sizes:
        sys.exit(f"{map_dir}: 没找到 LS2MAP 文件")
    lines = [
        "// Code generated by tools/gen-mapsizes.py; DO NOT EDIT.",
        "",
        "package gamedata",
        "",
        "// mapSizes 是每张地图的格子宽高（从 LS2MAP 文件头读），用于把遇敌区域的矩形裁到地图边界。",
        "var mapSizes = map[int][2]int{",
    ]
    for floor in sorted(sizes):
        w, h = sizes[floor]
        lines.append(f"\t{floor}: {{{w}, {h}}},")
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{map_dir}: {len(sizes)} 张地图的尺寸 → {OUT}")
    for line in dup:
        print(f"诊断: {line}")


if __name__ == "__main__":
    main()
