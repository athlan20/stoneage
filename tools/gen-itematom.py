#!/usr/bin/env python3
"""生成 server/gamedata/itematom.tsv：原子表（STAGE-205，合成用，见 docs/synthesis.md 第 2 节）。

列：原子下标 名字 魔法标志 编号。原子下标就是行序（原版 ITEM_getAtomIndexByName 的返回值）；
魔法标志和编号原版只存不用，照原样保留。数据来自 gmsv/data/itematom.txt（GBK）。

用法：python3 tools/gen-itematom.py [itematom.txt 路径]
不传路径时用仓库里的 original-data/gmsv/data/itematom.txt。
"""

import sys
from pathlib import Path

from atomtable import load_atoms

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "original-data/gmsv/data/itematom.txt"
OUTPUT = ROOT / "server/gamedata/itematom.tsv"


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    atoms = load_atoms(src)
    body = "\n".join(f"{i}\t{name}\t{magic}\t{num}" for i, (name, magic, num) in enumerate(atoms))
    OUTPUT.write_text(
        "# generated by tools/gen-itematom.py; DO NOT EDIT. 列：原子下标\t名字\t魔法标志\t编号\n"
        f"{body}\n",
        encoding="utf-8",
    )
    print(f"{src}: {len(atoms)} 个原子 → {OUTPUT}")


if __name__ == "__main__":
    main()
