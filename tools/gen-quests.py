#!/usr/bin/env python3
"""从原版服务端的 gmsv/data/jobdaily.txt 生成任务表 server/gamedata/quests.tsv（STAGE-86，docs/ui.md 任务页）。

jobdaily.txt 是 GBK 编码，每个任务两行（列序：任务编号|事件|任务名|状态）：
  任务编号|ENDEV=事件号|任务名|已完成    完成后事件号对应的位为 1
  任务编号|NOWEV=事件号|任务名|进行中    进行中事件号对应的位为 1
同一个任务编号的两行合并成一条：完成事件号、进行中事件号各取自对应的那一行。

原版把这些事件位存在角色身上（完成位 6×32、进行中位 6×32，只用到序号），
新服务端不照搬位图，只按任务编号存进度（characters 之外的 character_quests 表），
事件号只留在 TSV 里供对照原版。

已知异常：第 61 号“动物园任务 拿里拉拉的凯”的两个事件号都是 0。事件 0 不能代表一个任务
（没有可对照的位），这里跳过它，不收进任务表；原版是否真有这个任务，留待对照原版确认。

名字里的连续空格（如“猜谜3兄弟  拿蓝暴”）压成一个空格，和需求里的写法一致。

输出列（UTF-8，用 Tab 分隔）：任务编号 任务名 完成事件号 进行中事件号

用法：python3 tools/gen-quests.py [数据目录]
不传目录时用 original-data/gmsv/data。

STAGE-89：生成时还校验任务→百科攻略的对照表 tools/quest-wiki-map.json，每个任务编号都要有结论
（有攻略填词条，没有就填空数组），对照表里不能多出任务表没有的编号。
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DATA = ROOT / "original-data/gmsv/data"
OUT = ROOT / "server/gamedata/quests.tsv"
WIKI_MAP = ROOT / "tools/quest-wiki-map.json"

# 原版的事件号 0 不能代表任务，见文件头。
SKIP_EVENTS = {0}

# STAGE-333：自定义任务（不在 jobdaily.txt 里）：英雄岛“萨姆吉尔的勾玉”，任务编号 111，完成和进行中都是事件 185。
# 事件 185 在 jobdaily 和原版脚本里都没有用到（tools/npc_event_overlay.py 的 GOUYU_EVENT）。
EXTRA_QUESTS = {111: ("萨姆吉尔的勾玉", 185, 185)}

LINE = re.compile(r"^(\d+)\|(ENDEV|NOWEV)=(-?\d+)\|(.*)\|(已完成|进行中)$")
SPACES = re.compile(r"\s+")


def main(src: Path, dst: Path):
    quests = {}  # 任务编号 -> {"name": 名字, "end": 完成事件号, "now": 进行中事件号}
    for lineno, raw in enumerate(src.read_bytes().decode("gbk").splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"{src}:{lineno}: 格式不对：{line}")
        no, kind, event, name, _ = m.groups()
        no, event = int(no), int(event)
        q = quests.setdefault(no, {"name": SPACES.sub(" ", name).strip(), "end": None, "now": None})
        if q["name"] != SPACES.sub(" ", name).strip():
            sys.exit(f"{src}:{lineno}: 任务 {no} 的两行名字不一样")
        q["end" if kind == "ENDEV" else "now"] = event

    for no, (name, end, now) in EXTRA_QUESTS.items():
        if no in quests or any(q["end"] == end or q["now"] == end for q in quests.values()):
            sys.exit(f"自定义任务 {no} 的编号或事件号 {end} 已被原版任务占用")
        quests[no] = {"name": name, "end": end, "now": now}
    out = [
        "# generated by tools/gen-quests.py; DO NOT EDIT. 任务表（STAGE-86，docs/protocol.md 5.44）。"
        "列：任务编号 任务名 完成事件号 进行中事件号（来自 jobdaily.txt；第 61 号事件号为 0，已跳过）",
    ]
    skipped = []
    kept = []
    for no in sorted(quests):
        q = quests[no]
        if q["end"] in SKIP_EVENTS or q["now"] in SKIP_EVENTS:
            skipped.append(no)
            continue
        kept.append(no)
        out.append(f"{no}\t{q['name']}\t{q['end']}\t{q['now']}")
    check_wiki_map(set(kept))
    with open(dst, "w", encoding="utf-8") as w:
        w.write("\n".join(out) + "\n")
    print(f"写入 {dst}：{len(out) - 1} 个任务，跳过 {skipped}")


def check_wiki_map(numbers):
    """对照表（STAGE-89）要和任务表的编号完全一致：缺了的任务没有结论，多出的编号任务表里没有。"""
    table = json.loads(WIKI_MAP.read_text(encoding="utf-8"))
    mapped = {int(k) for k in table if not k.startswith("_")}
    missing = sorted(numbers - mapped)
    extra = sorted(mapped - numbers)
    if missing or extra:
        sys.exit(f"{WIKI_MAP}：任务 {missing} 没有攻略结论（有攻略填词条，没有填 []），多余的编号 {extra}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) / "jobdaily.txt" if len(sys.argv) > 1 else DEFAULT_DATA / "jobdaily.txt", OUT)
