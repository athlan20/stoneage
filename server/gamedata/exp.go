// NextExp 返回从 level 升到 level+1 这一级需要的经验（升级即从经验里扣除）；已是最高级返回 -1。
func NextExp(level int) int64 {
	if level < 1 || level+1 >= len(needLevelUp) {
		return -1
	}
	return needLevelUp[level+1]
}

// rankExpCoef 是经验公式的品质系数（ENEMY_getExp 的 ranktbl）：资质越好经验越多。
var rankExpCoef = [...]float64{2.5, 2.0, 1.5, 1.0, 0.5, 0.0}

// EnemyExp 是打倒一只怪得到的基础经验（ENEMY_getExp）：基础表加品质系数 × 等级。
// 原版公式还有一段 alpha（会心、反击、捕捉难度和异常状态概率列的加成），
// 这些列一期没有从 enemybase.txt 提取，先按 0 处理。
func EnemyExp(level, rank int) int64 {
	if level < 1 || level > len(baseExpTbl) {
		return 1
	}
	coef := 0.0
	if rank >= 0 && rank < len(rankExpCoef) {
		coef = rankExpCoef[rank]
	}
	ret := int64(float64(baseExpTbl[level-1]) + coef*float64(level))
	if ret < 1 {
		return 1
	}
	return ret
}
